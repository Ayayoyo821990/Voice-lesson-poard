// node scripts/synthetic.js --dir example2
// ENGINE TESTING ONLY. Turns <dir>/script.json (sentences) into a fake recording: segments.json + words.json with
// invented, evenly paced timings, and voice.wav with a short click on every word start (so sync can be heard).
// Nothing here is a real voice; every output is marked "synthetic". Replace all three files with a real recording
// (ffmpeg silencedetect + a recognizer) before making a lesson for students.
const path = require('path'), fs = require('fs');
const ROOT = path.resolve(__dirname, '..');
const i = process.argv.indexOf('--dir'), dir = i > 0 ? process.argv[i + 1] : null;
if (!dir) throw new Error('usage: node scripts/synthetic.js --dir <folder inside the skill>');
const D = path.resolve(ROOT, dir);
if (path.relative(ROOT, D).startsWith('..')) throw new Error(`path outside the skill folder refused: ${dir}`);
const S = JSON.parse(fs.readFileSync(path.join(D, 'script.json'), 'utf8'));
const P = { lead: 0.2, word: 0.16, letter: 0.06, gap: 0.05, comma: 0.3, sentence: 0.6, tail: 0.4, ...S.pace };

const letters = w => w.replace(/[ً-ْ،:.!؟?]/g, '').length;   // ignore harakat and punctuation
const segments = [], words = []; let t = P.lead;
S.sentences.forEach((text, k) => {
  const seg = { id: k + 1, text, start: +t.toFixed(3) }, pauses = [];
  text.split(/\s+/).filter(Boolean).forEach((w, j, all) => {
    const d = P.word + P.letter * letters(w);
    words.push({ word: w.replace(/[،:.!؟?]/g, ''), start: +t.toFixed(3), end: +(t + d).toFixed(3), confidence: 0.99 });
    t += d;
    if (j < all.length - 1) {
      if (/[،:]$/.test(w)) { pauses.push([+t.toFixed(3), +(t + P.comma).toFixed(3)]); t += P.comma; }
      else t += P.gap;
    }
  });
  seg.end = +t.toFixed(3); if (pauses.length) seg.inner_pauses = pauses;
  segments.push(seg); t += P.sentence;
});
const duration = +(t - P.sentence + P.tail).toFixed(3);
const WARN = 'SYNTHETIC timing generated by scripts/synthetic.js for engine testing only. Not a recording; not for students.';
fs.writeFileSync(path.join(D, 'segments.json'), JSON.stringify({ synthetic: true, warning: WARN, audio: `${dir}/voice.wav`, duration, pace: P, segments }, null, 1));
fs.writeFileSync(path.join(D, 'words.json'), JSON.stringify({ synthetic: true, warning: WARN, words }, null, 1));

// voice.wav: 22.05 kHz mono 16-bit silence with a 35 ms click per word (higher pitch on sentence starts)
const SR = 22050, N = Math.round(duration * SR), pcm = new Int16Array(N), starts = new Set(segments.map(s => s.start));
for (const w of words) {
  const f = starts.has(w.start) ? 1320 : 880, s0 = Math.round(w.start * SR), len = Math.round(0.035 * SR);
  for (let n = 0; n < len && s0 + n < N; n++) pcm[s0 + n] = Math.round(0.3 * 32767 * Math.sin(2 * Math.PI * f * n / SR) * Math.sin(Math.PI * n / len));
}
const hdr = Buffer.alloc(44);
hdr.write('RIFF', 0); hdr.writeUInt32LE(36 + N * 2, 4); hdr.write('WAVE', 8); hdr.write('fmt ', 12); hdr.writeUInt32LE(16, 16);
hdr.writeUInt16LE(1, 20); hdr.writeUInt16LE(1, 22); hdr.writeUInt32LE(SR, 24); hdr.writeUInt32LE(SR * 2, 28); hdr.writeUInt16LE(2, 32); hdr.writeUInt16LE(16, 34);
hdr.write('data', 36); hdr.writeUInt32LE(N * 2, 40);
fs.writeFileSync(path.join(D, 'voice.wav'), Buffer.concat([hdr, Buffer.from(pcm.buffer)]));
console.log(`${dir}: ${segments.length} sentences, ${words.length} words, ${duration} s — SYNTHETIC`);
segments.forEach(s => console.log(` seg ${s.id} ${s.start}-${s.end}: ` + s.text.split(/\s+/).map((w, j) => `${j}:${w}`).join(' ')));
